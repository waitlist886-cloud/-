GONE = {'烈火的先声·凯兰'}
CN = '零一二三四五六七八九十'
def cn(n):
    if n <= 10: return CN[n]
    if n < 20: return '十' + (CN[n-10] if n > 10 else '')
    return CN[n//10] + '十' + (CN[n%10] if n%10 else '')
def alive(card):
    return [x for x in L if x[2] <= card and (x[3] is None or x[3] >= card)]
if __name__ == '__main__':
    import sys
    out = []
    for c in range(1, 22):
        a = alive(c)
        items = []
        for x in a:
            tag = []
            if x[2] == c and c > 1: tag.append('新上表')
            if x[3] == c: tag.append('不知所终' if x[0] in GONE else '殁于这一段')
            name, alias = x[0], []
            if name.endswith('）'):
                name, rest = name[:-1].split('（', 1)
                alias = [rest]
            parts = alias + tag
            items.append(name + ('（' + '，'.join(parts) + '）' if parts else ''))
        out.append('%d|%s位|%s' % (c, cn(len(a)), '、'.join(items)))
    open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
