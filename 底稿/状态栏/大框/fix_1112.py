import re as _re
_PAREN = _re.compile(r'^/([^/\[\]()|?*+{}\\]{1,12})\[（\(\]/$')


def card_triggers(lb):
    n = 0
    for e in lb:
        tw = e.get('triggerWords') or []
        for w in list(tw):
            m = _PAREN.match(w)
            if not m:
                continue
            name = m.group(1)
            add = '/§(?:角色|话)｜' + name + '/'
            if name in tw or add in tw:
                continue
            if len(tw) >= 20:
                continue
            tw.append(add)
            n += 1
    return n


def _once(s, a, b, what):
    assert s.count(a) == 1, ('对不上', what, s.count(a), a[:60])
    return s.replace(a, b)


def system(sp, four):
    for what, a, b, scope in SYS:
        if scope == 'both' or (scope == 'four') == four:
            sp = _once(sp, a, b, '主提示词 ' + what)
    return sp


def rear(rp, four):
    for what, a, b, scope in REAR:
        if scope == 'both' or (scope == 'four') == four:
            rp = _once(rp, a, b, '后置词 ' + what)
    return rp


def _body(e):
    return e.get('content') or ''


def lore_edits(lb, four=False):
    n = 0
    for head, eds in LORE_EDITS.items():
        idx = [i for i, e in enumerate(lb) if _body(e).lstrip().startswith(head)]
        assert len(idx) == 1, (head, idx)
        c = lb[idx[0]]['content']
        for ed in eds:
            what, a, b = ed[:3]
            scope = ed[3] if len(ed) > 3 else 'both'
            if not (scope == 'both' or (scope == 'four') == four):
                continue
            c = _once(c, a, b, head + ' ' + what)
            n += 1
        lb[idx[0]]['content'] = c
    for head, (drop, add) in TRIG_EDIT.items():
        idx = [i for i, e in enumerate(lb) if _body(e).lstrip().startswith(head)]
        assert len(idx) == 1, (head, idx)
        tw = lb[idx[0]]['triggerWords']
        if all(w in tw for w in add):
            continue
        for w in drop:
            assert w in tw, ('触发里没有这个词', head, w)
            tw.remove(w)
        tw.extend(add)
        assert len(tw) <= 20, (head, len(tw))
        n += 1
    n += card_triggers(lb)
    return n


