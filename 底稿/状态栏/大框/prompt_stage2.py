import re


def _once(s, a, b, what):
    assert s.count(a) == 1, ('第二段对不上', what, s.count(a), a[:50])
    return s.replace(a, b)


def _line(s, start, what):
    m = re.findall(r'^' + re.escape(start) + r'[^\n]*$', s, re.M)
    assert len(m) == 1, ('第二段找不到这一行', what, len(m))
    return m[0]


