def residents(lb):
    """四份常驻各补三句、改一句。返回各份添了多少字"""
    out = {}
    for era, head in HEADS.items():
        hit = [e for e in lb if (e.get('content') or '').startswith(head + '\n')]
        assert len(hit) == 1, (era, len(hit))
        e = hit[0]
        c = e['content']
        n0 = len(c)
        assert '立绘:名' not in c and '地图页' not in c and '§技' not in c, (era, '已经补过')
        c = _once(c, MONEY_OLD, MONEY_NEW, era + '钱')
        if era == '月银纪':     # 这一份是一整段，不分条，接在记忆那一句后头
            a = '§记忆 的时间写成 `1690-花信-上旬三日 14:05–15:20`。'
            c = _once(c, a, a + ROAD[era] + '。' + ART_LINE + '，路人写 `路人`。' + PLACE_LINE + '。', era + '记忆')
        else:
            ln = _line(c, '- 记忆：§记忆 的时间写成', era + '记忆')
            c = c.replace(ln, ln + '\n- 路：' + ROAD[era] + '。\n- 立绘：' + ART_LINE + '，路人写 `路人`。\n- 地点：' + PLACE_LINE + '。')
        e['content'] = c
        out[era] = len(c) - n0
    return out


