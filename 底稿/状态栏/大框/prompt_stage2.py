def system(sp):
    """sp 是第一段切完的主提示词。返回 (新主提示词, 1001 年底座地点的例子)"""
    # 旧版回复那一行拿掉，原地换成管住全部的那一句
    old = _line(sp, '上文里如果还有带标签的旧版回复', '旧版回复')
    assert old.endswith('旧好感按【关系阶段进阶】折算。'), old[-30:]
    sp = sp.replace(old, OPEN_NEW)
    # 底座：例子换成通用的；地点和四纪那一段换成一句
    sp = _once(sp, BASE_OLD, BASE_NEW, '底座例子')
    m = re.findall(r'地点从大到小写，带上地图上有的那个地名，比如 ([^\n]*?)，地图页靠它给玩家插旗。月银纪、纷争纪、山铜纪、迷宫纪前传的局，[^\n]*?不用凑地图上的地名）', sp)
    assert len(m) == 1, len(m)
    places = m[0]
    assert places.count('、') == 2 and '阿卡迪亚' in places, places
    sp = re.sub(r'地点从大到小写，带上地图上有的那个地名，比如 [^\n]*?不用凑地图上的地名）', lambda _: PLACE_NEW, sp)
    sp = _once(sp, ROAD_OLD, ROAD_NEW, '路')
    sp = _once(sp, '；月银纪、纷争纪、山铜纪写 `无印｜金 n 银 n 铜 n`，后两栏照那一纪的常驻，迷宫纪前传照前传的常驻）', '）', '旅印括号')
    sp = _once(sp, '稀有度 Common／Rare／Epic／Legend／Unique。', '稀有度 Normal／Rare／Epic／Legend／Unique。', 'Common')
    sp = _once(sp, ART_OLD, ART_NEW, '立绘')
