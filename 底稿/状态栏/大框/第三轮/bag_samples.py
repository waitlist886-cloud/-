def build(d):
    src = open(os.path.join(UP, d['src']), encoding='utf-8').read().replace('\r', '')
    out, done_g, done_b = [], False, False
    for line in src.split('\n'):
        if line.startswith('§装备｜'):
            if not done_g:
                out += d['gear'].strip().split('\n')
                done_g = True
        elif line.startswith('§物品｜') or line.startswith('§背包｜'):
            if not done_b:
                out += d['bag'].strip().split('\n')
                done_b = True
        elif line.startswith('§面板｜着装｜') and line.count('｜') > 2:
            out.append('§面板｜着装｜' + line.split('｜')[-1])   # 四纪的旧样本是五栏的老写法，换成现行的一栏（穿戴写在 §装备）
        else:
            out.append(line)
    assert done_g and done_b, d['src']
    open(os.path.join(HERE, d['out']), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print(d['out'], d['bag'].count('§物品'), '样')


if __name__ == '__main__':
    for d in (MAZE, MOON, STRIFE, BRONZE):
        build(d)
