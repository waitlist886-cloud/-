def build(base, lines):
    src = io.open(os.path.join(UP, base), encoding='utf-8').read().replace('\r', '').split('\n')
    i = next(k for k, l in enumerate(src) if l.startswith('§正文｜'))
    j = i + 1
    while not src[j].strip():
        j += 1
    out = src[:j + 1] + ['']
    for l in lines:
        out += [l] if l.startswith('§') else ['', l, '']
    return '\n'.join(out + [''] + src[j + 1:])


