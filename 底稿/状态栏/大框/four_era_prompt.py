def _once(s, a, b, what):
    assert s.count(a) == 1, ('对不上', what, s.count(a), a[:60])
    return s.replace(a, b)


def adapt_lore(lb, nb):
    """四纪常驻里说底座、面板怎么换的那几段，照大框的记录行改"""
    import re
    done = []
    for head, edits in RESIDENT.items():
        hit = [i for i in range(nb, len(lb)) if lb[i]['content'].startswith(head)]
        assert len(hit) == 1, (head, hit)
        i = hit[0]
        c = lb[i]['content']
        for what, a, b in edits:
            c = _once(c, a, b, head + what)
        for a, b in GENERIC:
            c = c.replace(a, b)
        left = [t for t in OLD_TERMS if t in c]
        assert not left, (head, '还剩', left, [m.group(0)[:80] for t in left for m in re.finditer(r'[^。\n]*' + t + r'[^。\n]*', c)][:6])
        lb[i]['content'] = c
        done.append(i)
    print('四纪常驻改了', done)
    return lb


