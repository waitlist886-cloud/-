OPTIONS = [('难度', '【难度：普通/困难】'), ('节奏', '【节奏：均衡/慢速/快速/大纲】'), ('调子', '【调子：史诗/日常/民谣/阴郁/歌剧/荒诞】')]


def options(o):
    items = [dict(x) for x in o['items']]
    have = {x['label'] for x in items}
    for label, value in OPTIONS:
        if label not in have:
            items.append({'order': len(items), 'label': label, 'type': 'SET-INPUT', 'value': value})
    return {'items': items}


