def seed_entries():
    rnd = random.Random(1110)
    names, seen = [], set()
    while len(names) < 25:
        h, t, s = rnd.choice(HEAD), rnd.choice(TAIL), rnd.choice(SUR)
        if h == t or (h, t) in seen:
            continue
        seen.add((h, t))
        names.append(('本轮要是现编有名有姓的新人物，名字照这几个音起，头一个字取 %s 的音，收尾落在 %s 上，有姓的话姓里带 %s。'
                      '照这个人的出身化开，跟名录里的人不同名，也不只差一个字。' % (h, t, s), 4))
    pers = []
    for _ in range(25):
        pers.append(('本轮新登场、要多写几句的人，性格从这里起，要的是%s，说话%s，怕%s，有个小毛病，%s。照他的身份和处境化开，不照抄字面。'
                     % (rnd.choice(WANT), rnd.choice(TALK), rnd.choice(FEAR), rnd.choice(HABIT)), 4))
    body = []
    for _ in range(20):
        body.append(('本轮新登场的人头一回写到样子，身形%s，叫人记得住的一处是%s。往后照这个写。' % (rnd.choice(SHAPE), rnd.choice(MARK)), 5))
    return [_entry('种子·起名的音', ['/^/'], contents=names, prio=10),
            _entry('种子·性格', ['/^/'], contents=pers, prio=11),
            _entry('种子·身形', ['/^/'], contents=body, prio=12)]


