def switch_entries():
    out = [_entry('难度·困难', _sw('难度', '困难'), HARD, rng=('user', 'assistant'), depth=2, prio=20),
           _entry('节奏·慢速', _sw('节奏', '慢速'), SLOW, rng=('user', 'assistant'), depth=2, prio=21),
           _entry('节奏·快速', _sw('节奏', '快速'), FAST, rng=('user', 'assistant'), depth=2, prio=22),
           _entry('节奏·大纲', _sw('节奏', '大纲'), OUTLINE, rng=('user', 'assistant'), depth=2, prio=23)]
    for k, (name, (guide, demo)) in enumerate(TONES.items()):
        txt = '# 调子·%s\n§底座 写着 调子 %s 的局照这一条。%s%s%s' % (name, name, guide, TONE_TAIL, demo)
        out.append(_entry('调子·' + name, _sw('调子', name), txt, rng=('user', 'assistant'), depth=2, prio=30 + k))
    return out


def entries(dice=True):
    """接在底卡后头的新条目。dice=False 时只给开关（风月没有加权条目）"""
    out = (dice_entries() + seed_entries() if dice else []) + switch_entries()
    return out


def strip(e):
    e = dict(e)
    e.pop('_name', None)
    return e


