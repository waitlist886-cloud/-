def lore_edits(lb):
    n = 0
    for head, eds in LORE_EDITS.items():
        idx = [i for i, e in enumerate(lb) if (e.get('content') or '').lstrip().startswith(head)]
        assert len(idx) == 1, (head, idx)
        c = lb[idx[0]]['content']
        for what, a, b in eds:
            c = _once(c, a, b, head + ' ' + what)
            n += 1
        lb[idx[0]]['content'] = c
    return n


