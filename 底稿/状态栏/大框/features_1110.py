PRIO0 = 9100


def _entry(name, trig, content=None, contents=None, rng=('user',), depth=1, prio=0):
    e = {'enabled': True, 'triggerWords': list(trig), 'triggerWordsType': 'OR', 'blackListWords': [], 'blackListWordsType': 'OR',
         'folder': FOLDER, 'priority': PRIO0 + prio, 'probability': 100, 'scanDepth': depth, 'triggerRange': list(rng),
         'impactRange': ['system']}
    if contents:
        assert sum(p for _, p in contents) == 100, (name, sum(p for _, p in contents))
        assert len(contents) <= 30
        e['contentMethod'] = 'weighted'
        e['contents'] = [{'content': c, 'probability': p} for c, p in contents]
    else:
        e['contentMethod'] = 'single'
        e['content'] = content
    e['_name'] = name
    return e


