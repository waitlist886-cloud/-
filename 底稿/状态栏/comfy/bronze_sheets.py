def fig(d, col, head, neck, hip, larm, rarm, lleg, rleg, r=26, w=22):
    """火柴人。larm、rarm、lleg、rleg 各是从肩或胯往外的点列。"""
    d.line([neck, hip], fill=col, width=w + 8)
    for chain in (larm, rarm):
        d.line([neck] + chain, fill=col, width=w, joint='curve')
    for chain in (lleg, rleg):
        d.line([hip] + chain, fill=col, width=w + 2, joint='curve')
    d.ellipse((head[0] - r, head[1] - r, head[0] + r, head[1] + r), fill=col)


def arrow(d, a, b, col=(255, 255, 255), w=6):
    d.line([a, b], fill=col, width=w)
    import math
    t = math.atan2(b[1] - a[1], b[0] - a[0])
    for s in (-0.5, 0.5):
        d.line([b, (b[0] - 26 * math.cos(t + s), b[1] - 26 * math.sin(t + s))], fill=col, width=w)


