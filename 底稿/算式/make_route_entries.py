def table(era, pairs, default):
    P = R.load(era)
    out = []
    for p in pairs:
        a, b = p[0], p[1]
        modes = p[2] if len(p) > 2 and p[2] else default
        lab = p[3] if len(p) > 3 else None
        note = p[4] if len(p) > 4 else ''
        s, _ = R.row(P, a, b, modes, lab)
        out.append(s + note)
    return '\n'.join(out) + '\n'


