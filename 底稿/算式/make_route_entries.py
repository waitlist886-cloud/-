def wd(key, mult, wait=0.0):
    nav = SEA[key] / mult
    return nav + math.floor(nav / 10) * 0.5 + wait


def sea(label, parts, note=''):
    """parts：[(说法, [(哪一段, 一天顶走路几天, 候闸候潮几天)…])]，一格里几段的天数加起来"""
    return '- %s｜%s%s' % (label, '，'.join('%s%s' % (name, R.say(sum(wd(*s) for s in segs))) for name, segs in parts), note)


