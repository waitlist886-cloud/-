def main():
    done = miss = 0
    texts = {}
    for gid, who, old, new in EDITS:
        p = os.path.join(HERE, gid + '.json')
        s = texts.setdefault(p, open(p, encoding='utf-8').read())
        if new in s:
            print('  已改过  %s %s' % (gid, who))
            continue
        n = s.count(old)
        if n != 1:
            print('！对不上（%d 处）  %s %s｜%s' % (n, gid, who, old[:28]))
            miss += 1
            continue
        texts[p] = s.replace(old, new)
        done += 1
        print('  改  %s %s' % (gid, who))
    print('改 %d 处，对不上 %d 处%s' % (done, miss, '' if APPLY else '（只报，没写）'))
    if APPLY and not miss:
        for p, s in texts.items():
            open(p, 'w', encoding='utf-8', newline='\n').write(s)
        print('写了盘')


if __name__ == '__main__':
    main()
