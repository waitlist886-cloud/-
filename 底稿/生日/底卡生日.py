def fix(text, i):
    old, new = B[i]
    lines = text.split('\n')
    hit = 0
    for k, l in enumerate(lines):
        if (l.startswith('固定锚定') or l.startswith('锚定：')) and ('｜' + old + '｜') in l:
            lines[k] = l.replace('｜' + old + '｜', '｜' + new + '｜', 1)
            hit += 1
    assert hit == 1, ('锚定对不上', i, old, hit)
    return '\n'.join(lines)


if sys.argv[1] == 'pub':
    card = json.load(open(sys.argv[2], encoding='utf-8'))
    lb = card['prompt']['lorebook']
    for i in B:
        lb[i]['content'] = fix(lb[i]['content'], i)
    card['changelog'] = '11-08 档案改生日：旅伴和任务人物的岁数换成出生日期，岁数照当天的日期现算，玩家从哪一年进来都对。' + card['changelog']
    assert len(card['changelog']) <= 2048
