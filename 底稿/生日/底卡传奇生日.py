def add(i):
    born, look = L[i]
    s = '｜' + (born if born.startswith('生年') else '生于' + born)
    if look:
        s += '｜外表' + look
    return s


def fix(sec, i):
    lines = sec.split('\n')
    ks = [k for k, l in enumerate(lines) if l.startswith('固定锚定：')]
    assert len(ks) == 1, ('固定锚定不止一行或者没有', i, len(ks))
    l = lines[ks[0]]
    assert '生于' not in l and '生年' not in l, ('已经有生日了', i)
    end = '。' if l.endswith('。') else ''
    lines[ks[0]] = l[:len(l) - len(end)] + add(i) + end
    return '\n'.join(lines)


root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '底卡洗稿')
done = set()
for fn in sorted(os.listdir(root)):
    p = os.path.join(root, fn)
    raw = open(p, encoding='utf-8', newline='').read()
    crlf = '\r\n' in raw
    s = raw.replace('\r\n', '\n')
    parts = re.split(r'(?m)^(## #\d+ )', s)
    changed = False
    for k in range(1, len(parts), 2):
        i = int(re.match(r'## #(\d+)', parts[k]).group(1))
        if i not in L:
            continue
        sec = fix(parts[k + 1], i)
        new = add(i)[1:]
        # 放行那一行添上新起的年月日，wash_check 就不把生年当成凭空多出来的数
        if re.search(r'(?m)^- 放行：', sec):
            sec = re.sub(r'(?m)^(- 放行：[^\n]*)$', lambda m: m.group(1) + '、' + new, sec, count=1)
        else:
            sec = re.sub(r'(?m)^(- 底本哈希：[^\n]*)$', lambda m: m.group(1) + '\n- 放行：' + new, sec, count=1)
        parts[k + 1] = sec
        done.add(i)
        changed = True
    if changed:
        s = ''.join(parts)
        if crlf:
            s = s.replace('\n', '\r\n')
        open(p, 'w', encoding='utf-8', newline='').write(s)
        print('改了', fn)
print('洗稿层改了', len(done), '条；没找到的', sorted(set(L) - done))
