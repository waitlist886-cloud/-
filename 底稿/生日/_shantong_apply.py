def parse(f):
    L = open(f, encoding='utf8').read().split('\n')
    mo = re.search(r'^开局：山铜纪(\d+)年(.*)', "\n".join(L), re.M)
    if not mo:
        return L, -1, None
    oy = int(mo.group(1))
    mm = re.search('(' + '|'.join(MO) + ')', mo.group(2)[:40])
    om = MO.index(mm.group(1)) if mm else None
    return L, oy, om


ents = []
files = sorted(glob.glob('E:/aldran_art/山铜纪/parts*/[a-i]_*.md'))
for f in files:
    L, oy, om = parse(f)
    for i, l in enumerate(L):
        if l.startswith('固定锚定：') and '生于' not in l:
            p = l.split('｜')
            name = re.sub(r'（.*', '', p[3][3:])
            f5 = p[5]
            if f5.startswith('看着八九岁'):
                A = 50
            else:
                A = int(re.search(r'(\d+)岁', f5).group(1))
            py = re.search(r'（(\d+)年）', f5)
            Y = int(py.group(1)) if py else oy
            m = om if Y == oy else None
            ents.append(dict(f=f, i=i, name=name, A=A, Y=Y, m=m, f5=f5))


def age(by, b, Y, m):
    return Y - by - (1 if b > m else 0)


G = defaultdict(list)
for e in ents:
    G[e['name']].append(e)
BY = {}
for n, es in G.items():
    b = B[n][0]
    if n in FIX:
        BY[n] = FIX[n]
        continue
    best = None
    for by in range(min(e['Y'] - e['A'] for e in es) - 3, max(e['Y'] - e['A'] for e in es) + 3):
        mis = 0
        for e in es:
            if e['m'] is None:
                d = min(abs(e['A'] - (e['Y'] - by)), abs(e['A'] - (e['Y'] - by - 1)))
            else:
                d = abs(e['A'] - age(by, b, e['Y'], e['m']))
            mis += d
        if best is None or mis < best[0]:
            best = (mis, by)
    BY[n] = best[1]


def fmt(n):
    b, x, d = B[n]
    by = BY[n]
    if by <= 0:
        era, y = '纷争纪', 11033 + by
    else:
        era, y = '山铜纪', by
    return f'{era}{y}年·{MO[b]}·{XUN[x]}{cn(d)}日'


