    for ch, name, desc, items in chapters:
        for it in items:
            main, task = it[0], it[1]
            inter = len(it) > 2 and it[2]
            want['%s·主线｜%s' % (era, main)] = ['题：奥尔德兰的旅印｜%s·%s%s｜【%s】' % (part, ch, '·间奏' if inter else '', task), '章：《%s》｜%s' % (name, desc)]
