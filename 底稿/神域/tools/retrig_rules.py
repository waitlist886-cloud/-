# 一次性：规则层各条的触发收窄（11-22）。共用条目不挡纪元，原来的词里高座、降临、神战、神骸、登神、秘仪这些在全卷里成百上千回，会白醒。
#   python -I -X utf8 底稿/神域/tools/retrig_rules.py
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
P = os.path.join(ROOT, '底稿', '神域', '规则层_第一版.md')
NEW = {
    '神的面板': '神力等级|神域栏|候火那一档|燃火那一档|执柄那一档|执柄的神|擎世|神力几级',
    '秘仪': '立秘仪|秘仪三样|立下秘仪|薪、誓、名|破了誓的神|凡极以后怎么走',
    '六步升华': '六步升华|第一步升华|神躯六相|擎山之膂|不朽之血|无迹之步|不竭之泉|千面之心|应名之耳|三百级以后',
    '点燃神火': '点燃神火|怎么登神|要登神|想登神|空着的神位|坐上空坛',
    '一级一得': '一级一得|神力升了|第二份权柄|第三份权柄|神职超载',
    '七柱七十二域': '七十二域|正位和逆位|归哪一域|三迹|这一域的逆位|这一域的正位',
    '神域专长（上）': '神域专长|瞬临|灭却|一言成律|擎天巨相|封神铸器|神火不落',
    '神域专长（下）': '神域专长|地上神国|封柄|夺柄|万灵应召',
    '神国与高座': '神国里|神国的|进神国|国律|国相|高座方圆|打进高座',
    '神的三相': '行走相|神的三相|本相和显相|神怎么下来|神下到人间|神扮成',
    '信众与蚀名': '底噪|信仰之毒|蚀名|收信众|料理信仰',
    '神战': '对神手段|怎么打神|神对神|凡人对神|跟神动手',
    '弑神与夺柄': '弑神|杀死一位神|杀得死神|夺柄|取柄',
    '凡躯持柄': '持柄|权柄在身|拿了权柄|分到的权柄|身上带着权柄',
}
s = open(P, encoding='utf-8').read()
parts = re.split(r'(?m)^(?=## )', s)
n = 0
for i, p in enumerate(parts):
    m = re.match(r'## 纷争纪·规则｜(.+?)\s*\n', p)
    if not m or m.group(1) not in NEW:
        continue
    rx = NEW[m.group(1)]
    re.compile(rx)
    q, k = re.subn(r'(?m)^(> 条目设置：.*?〔纷争纪·正则〕、)`/.+/`', lambda mm: mm.group(1) + '`/' + rx + '/`', p)
    assert k == 1, m.group(1)
    parts[i] = q
    n += 1
assert n == len(NEW), n
open(P, 'w', encoding='utf-8', newline='\n').write(''.join(parts))
print('换了', n, '条')
