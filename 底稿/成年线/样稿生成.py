# 从洗稿层取三位的条目，套样稿的替换，写卡面检查稿。每个旧串必须正好出现一次。
import re, glob, sys
ROOT = sys.argv[1]; OUT = sys.argv[2]
def entries():
    d = {}
    for f in glob.glob(ROOT + '/底卡洗稿/*.md'):
        t = open(f, encoding='utf-8').read()
        for m in re.finditer(r'(?m)^## #(\d+) [^\n]*\n(?:- [^\n]*\n)*\n````\n(.*?)\n````', t, re.S):
            d[int(m.group(1))] = m.group(2)
    return d
E = entries()
def tail_append(text, line_prefix, add):
    lines = text.split('\n')
    hit = [i for i, l in enumerate(lines) if l.startswith(line_prefix)]
    assert len(hit) == 1, (line_prefix, len(hit))
    lines[hit[0]] += add
    return '\n'.join(lines)
def rep(text, pairs, tag):
    for a, b in pairs:
        n = text.count(a)
        assert n == 1, (tag, a[:30], n)
        text = text.replace(a, b)
    return text
