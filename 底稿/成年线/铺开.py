def sha12(t):
    return hashlib.sha1(t.encode('utf-8')).hexdigest()[:12]


def main():
    card = json.load(open(CARD, encoding='utf-8'))
    lb = card['prompt']['lorebook']
    todo = set(W) | set(TITLES)
    done, out_files = set(), {}
    for f in sorted(glob.glob(os.path.join(ROOT, '底卡洗稿', '*.md'))):
        text = open(f, encoding='utf-8').read()
        heads = list(re.finditer(r'^## #(\d+) (.*)$', text, re.M))
        if not any(int(m.group(1)) in todo for m in heads):
            continue
        pieces, last = [], 0
        for k, m in enumerate(heads):
            idx = int(m.group(1))
            end = heads[k + 1].start() if k + 1 < len(heads) else len(text)
            pieces.append(text[last:m.start()])
            block = text[m.start():end]
            last = end
            if idx not in todo:
                pieces.append(block); continue
            bm = re.search(r'^````[^\n]*\n(.*?)\n````\s*$', block, re.M | re.S)
            assert bm, (idx, '没找到正文')
            body = bm.group(1)
            spec = W.get(idx, {})
            for a, b in spec.get('reps', []):
                n = body.count(a)
                assert n == 1, (idx, a[:30], n)
                body = body.replace(a, b)
            for prefix, add in spec.get('tails', []):
                lines = body.split('\n')
                hit = [i for i, l in enumerate(lines) if l.startswith(prefix)]
                assert len(hit) == 1, (idx, prefix, len(hit))
                lines[hit[0]] += add
                body = '\n'.join(lines)
            head_line = block.split('\n', 1)[0]
            meta = block[len(head_line) + 1:bm.start()]
            if idx in TITLES:
                a, b = TITLES[idx]
                first = body.split('\n', 1)[0]
                assert first.count(a) == 1, (idx, '标题行里没有', a)
                body = body.replace(a, b, 1)
                head_line = head_line.replace(a, b)
                src = lb[idx]['content']
                hm = re.search(r'^- 底本哈希：\s*([0-9a-f]{12})', meta, re.M)
                assert hm and hm.group(1) == sha12(src), (idx, '底本哈希跟 --card 对不上，先拿现在的补丁打一张底本')
                assert src.count(a) == 1, (idx, '底本里旧标题不是一处')
                meta = meta.replace(hm.group(0), '- 底本哈希：' + sha12(src.replace(a, b)))
            allow = spec.get('allow', [])
            if allow:
                am = re.search(r'^- 放行：(.*)$', meta, re.M)
                if am:
                    have = [x.strip() for x in am.group(1).split('、')]
                    meta = meta.replace(am.group(0), '- 放行：' + '、'.join(have + [x for x in allow if x not in have]))
                else:
                    hm2 = re.search(r'^- 底本哈希：.*$', meta, re.M)
                    meta = meta[:hm2.end()] + '\n- 放行：' + '、'.join(allow) + meta[hm2.end():]
            pieces.append(head_line + '\n' + meta + block[bm.start():bm.start(1)] + body + block[bm.end(1):])
            done.add(idx)
        pieces.append(text[last:])
        out_files[f] = ''.join(pieces)
    miss = todo - done
    assert not miss, ('洗稿层里没找到', sorted(miss))
    for f, t in out_files.items():
        if not DRY:
            open(f, 'w', encoding='utf-8').write(t)
        print(('（没写）' if DRY else '写了 ') + os.path.basename(f))
    print('改了 %d 条：%s' % (len(done), ' '.join('#%d' % i for i in sorted(done))))


main()
