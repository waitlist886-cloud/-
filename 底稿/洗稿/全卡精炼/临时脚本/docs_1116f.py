import io
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
APPLY = '--apply' in sys.argv
V12 = [a for a in sys.argv[1:] if not a.startswith('--')][0]
MB = '%.2f' % (int(V12) / 1e6)
ROOT = 'E:/aldran_art/'


def edit(path, pairs, inserts=()):
    raw = open(ROOT + path, 'rb').read().decode('utf-8')
    nl = '\r\n' if '\r\n' in raw else '\n'
    t = raw.replace('\r\n', '\n')
    for old, new in pairs:
        if t.count(old) != 1:
            raise SystemExit('%s｜对不上（%d 处）：%s' % (path, t.count(old), old[:60]))
        t = t.replace(old, new)
    for before, block in inserts:
        if t.count(before) != 1:
            raise SystemExit('%s｜插入点对不上（%d 处）：%s' % (path, t.count(before), before[:60]))
        if block.split('\n')[0] in t:
            raise SystemExit('%s｜已经插过了：%s' % (path, block.split('\n')[0][:40]))
        t = t.replace(before, block + '\n\n' + before)
    print('%s｜改 %d 处，插 %d 段｜%s' % (path, len(pairs), len(inserts), 'CRLF' if nl == '\r\n' else 'LF'))
    if APPLY:
        open(ROOT + path, 'wb').write(t.replace('\n', nl).encode('utf-8'))


