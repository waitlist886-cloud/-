def heads(path):
    out = []
    for i, line in enumerate(open(path, encoding='utf-8').read().replace('\r', '').split('\n'), 1):
        if line.startswith('## '):
            out.append((i, line[3:].strip()))
    return out


def sections(path):
    t = open(path, encoding='utf-8').read().replace('\r\n', '\n')
    idx = [m.start() for m in re.finditer(r'^## ', t, re.M)] + [len(t)]
    return [t[a:b] for a, b in zip(idx, idx[1:])]


