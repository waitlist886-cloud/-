import io
import json
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
BASE = 'C:/Users/waitl/codex_work/wash_1115'
args = [a for a in sys.argv[1:] if not a.startswith('--')]
FIX = None
if '--fix' in sys.argv:
    FIX = sys.argv[sys.argv.index('--fix') + 1]
    args = [a for a in args if a != FIX]

RULES = '''## 给这一回洗稿的人（先读这一节，再读 `洗稿说明.md` 和两份样稿）

这里跑不了命令。自查由派活的人替你跑，报的错会再发回来让你改，所以头一遍就照下面几条写准。上一回你洗这张卡，毛病都出在这几条上。

1. **只删不添。** 洗稿是把重复的话、用不上的交代拿掉。留下来的每一件事、每一个名字、每一个数、每一句引号里的话，都得在 `原/` 的同一个文件里找得到。不许替原稿补因果、补动机、补下场、补称呼、补形容，不许把两件事并成一件新的事，不许把原稿没说破的东西说破，不许把往后的事提前说。上一回添过“同归于尽”“他父亲死在队尾”“地主家的女儿”，还提前说了一个人的死，这一类一处也不许有。拿不准原稿有没有，就照原稿的说法写，或者不写。
2. **白话照旧是白话。** 原稿是通顺的白话。不许收成书面话和文言：卒于、伏诛、此后、仍、未、均、是否、遂、亦、乃、其、之所以这一类，原稿那一句里没有的就不用。“腰悬皮囊，装有图册与布袋”“她依约录名，便命书记请你离去”“旁人应退开”“并唤你同食”“不利于己”这一路也是文言，上一回整条旅伴条都写成了这样，不许有，照原稿的说法写（“腰上挂着一只皮囊，里头是图册和布袋”）。也不许抽掉“的、了、着、是、在、就、也、还、把”压成几个字一截的电报。句子要完整，有主语，读出来像人说的话。
3. **有画面的句子留整句。** 一个动作、一个比方、一句没说完的话，名号、誓词、头目登场、传奇出手、一个人凝名的那一下，照原句留，别压成一句交代。引号里的台词一个字不改，不删半句，不新写台词。
4. **收多少。** 幅度照样稿：主线一节留六成到七成半，旅伴条、人物、地点、遗迹、案子各节留六成半到八成，命星留七成半到九成。收短只有一个办法，删整句：同一件事在这一节里说了两遍的留一遍；别的条目里写着的来历、下场、经过，这里只提一句（来历住背景条，本事住命星，下场住旅伴条自己那一栏，经过住主线）；铺垫、过渡、重复的形容、绕着说的话整句拿掉；“玩家在场插手照玩家做的事走”“只取底座年份所在的那一段”这一类通用的规矩句拿掉。留下来的句子照原稿的样子，句子里的字一个不抽。**宁可留九成，也不许把句子压成电报**：上一回有一份为了凑数，把整节压成了“仅”“则”“仍”连成的短语，虚字抽得一个不剩，那一份整份作废了。删不动整句的节就照原稿留长。
5. **不许动的行**（细目在 `洗稿说明.md` 第三节）：`## ` 和 `### ` 标题行，`> 条目设置` 那一行，固定锚定、底座、体态数据那几行，`题：` `章：` `篇：` 几行，Special 星的头一段（【调用】底下、`- 被动` 以前），`## 星` 标题底下到头一颗星以前的那一段，文件末尾“这一份的设计备注”整节，标题带“凡世至强”的节整节。行尾的（★）和（#数字）照留。
6. **栏名一个字不换，栏不并不丢。** 身份、外貌、容貌评价、体态数据、装束、性格底色、底线、底座、能力、初见、关系、正史里的下场、【独立声口｜某某】、【好感增减｜某某】、裁定锁这些栏，原稿有的洗后都在、次序不变。星条里的被动、主动、修行关联、限制、世界反应、传承、只给 AI 各行照旧一行一条，机制用语（判定获得优势、CD、百分数、几回、多远）一个字不变。
7. **“这一段旅伴之间”原稿有几对就留几对**，一对一行。
8. 直接改 `稿/` 里的文件，文件名不变，UTF-8，不带 BOM。`原/` 不许动，不要联网，不要新建别的文件夹。照 `## ` 标题一节一节来：读一节，用编辑工具把这一节换成洗好的，一次只换一节，别整份重写（文件长，整份重写写不完）。命星那一节照 `### ` 一颗一颗换。整份洗完再交，别洗到一半停下，也别只洗前半。`稿/` 里跟 `原/` 一字不差的节就是还没洗的。
9. 洗完自己对一遍：`稿/` 里每个文件的 `## ` 标题跟 `原/` 一样多、一样的字；没有 ——、—、；、…、！这几种标点；没有月亮、月光这类字眼。
10. 交两样：`改动说明.md`（一节一行，多少字到多少字，并掉了什么、挪到了哪）和 `删除单.md`（从这个文件里彻底拿掉、别处也没有的事实，一条一行，没有就写“无”）。
11. **旅伴条“身份”那一行的开头照原稿留着。** 原稿开头是“维布克·艾希，人族哨兵，……”这样的全名、种族和行当，洗后这一行还得从全名起头，后头的来历可以收。上一回这一行常被收成“燕巢段城的哨兵”，名字和种族一起丢了。
12. **“正史里的下场”写的是这个人自己的事。** 哪一年、他做了什么、结果怎样，一件一件对着原稿留。可以把写别人的句子拿掉，不许把他自己的事拿掉，也不许把谁做的事安到另一个人身上。
13. **数和长短一个字不改。** “半天”不写成“大半天”，“几天以后几百里外才知道”不写成“传出几百里”，“十个回来三个”不写成“多半回不来”。条件句（要是……就……）不压成已经发生的事。
14. **一节洗完不许比原稿长。** 收短靠删整句、删重复，不靠改字。自查报了电报腔叫你改的时候，直接拿 `原/` 里同一节的原句换回来，再删掉重复的整句，不要自己往句子里添“的、了、着”凑数。背景条（旅途同行·背景）例外，来历从旅伴条挪进去以后可以比原来长。收不动的节照原稿留着，一个字不改，比改写一遍却没短要好。
'''


BOND = '''15. **这一份是羁绊章，上面第 6、7、11、12 条说的旅伴条栏目这里没有，不用管。** 一章是一个 `## ` 节。章里的 `### ` 小标题（序章、几幕、抉择点、尾声、结算这些）一个不少，名字不改。紧跟章标题的两行（“某某之章：【题】”那一行和“【人名】……”那一行）一个字不动。核心结、抉择点每一条路各自的结果、结算里伟业和信物的名字照原稿留。一章留六成到七成半：每一幕留剥开的那一层事和落点的那一个画面，铺垫、重复的心理、绕着说的话整句拿掉。尾声写的是这一章走通了的样子，不许改成别的结局，也不许把抉择点里别的路写没了。台词一个字不改。
'''


def one(job):
    d = '%s/%s' % (BASE, job)
    if not os.path.isdir(d):
        raise SystemExit('没有这个文件夹：' + d)
    ag = d + '/AGENTS.md'
    keep = d + '/AGENTS_codex.md'
    if not os.path.exists(keep):
        os.replace(ag, keep)
    src = open(keep, encoding='utf-8').read().replace('\r\n', '\n')
    # 拿掉叫它跑自查的那一段
    src = re.sub(r'\n做完在这个文件夹里跑[^\n]*\n', '\n', src)
    head, sep, tail = src.partition('\n交三样')
    body = head.rstrip('\n') + '\n\n' + RULES
    try:
        files = json.load(open(d + '/job.json', encoding='utf-8')).get('files', [])
    except Exception:
        files = []
    if files and all('羁绊' in os.path.basename(f) for f in files):
        body += BOND
    if FIX:
        names = [x.strip() for x in FIX.split('｜') if x.strip()]
        body += '\n## 这一回只做一件事\n\n这一份活上一位洗稿的人做到一半停了。`稿/` 里别的节都洗好了，**不要动**。只把下面几节照 `原/` 里同名文件的同一节重洗一遍：它们现在被压成了电报（虚字抽掉了，几个字一截）。照上面第 2、3 条写回完整的白话句子，篇幅留到原稿的七成上下，事实、数目、引语都对着原稿。\n\n' + '\n'.join('- `%s`' % n for n in names) + '\n\n做完在 `改动说明.md` 末尾添一段，写这几节各从多少字到多少字。\n'
    open(d + '/任务_Gemini.md', 'w', encoding='utf-8', newline='\n').write(body)
    open(ag, 'w', encoding='utf-8', newline='\n').write('# 这个文件夹的活\n\n照 `任务_Gemini.md` 做。先把它读完。\n')
    j = json.load(open(d + '/job.json', encoding='utf-8'))
    j['washer'] = 'gemini'
    json.dump(j, open(d + '/job.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('%s｜任务_Gemini.md %d 字%s' % (job, len(body), '｜只重洗 %d 节' % len(FIX.split('｜')) if FIX else ''))


for a in args:
    one(a)
