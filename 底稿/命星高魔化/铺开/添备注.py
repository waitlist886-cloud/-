def notes_file(page):
    m = re.match(r'(纷争纪|山铜纪|迷宫纪前传)_(.)', page)
    num = '一二三四五六七'
    if m:
        n = num.index(m.group(2)) + 1
        if m.group(1) == '纷争纪':
            d = os.path.join(D.ROOT, '纷争纪', 'parts' if n == 1 else 'parts%d' % n)
            fs = glob.glob(os.path.join(d, '*_notes.md'))
            return fs[0] if fs else None
        return os.path.join(D.ROOT, m.group(1), 'parts%d' % n, 'p9_notes.md')
    fs = D.page_files(page)
    return fs[0] if fs else None


pages = []
for r in D.read_tsv('全谱.tsv') + D.read_tsv('旅伴表.tsv'):
    if r['页'] not in pages:
        pages.append(r['页'])
n = 0
for p in pages:
    f = notes_file(p)
    if not f or not os.path.exists(f):
        print('找不到备注文件｜' + p)
        continue
    s = io.open(f, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in s else '\n'
    line = GEN + (EXTRA.get(p, ''))
    lines = s.split(nl)
    hit = [i for i, l in enumerate(lines) if MARK in l]
    if hit:
        lines[hit[0]] = line
        for i in hit[1:][::-1]:
            del lines[i]
    else:
        while lines and lines[-1].strip() == '':
            lines.pop()
        lines += [line, '']
    n += 1
    print('%s｜%s｜%s' % (p, os.path.relpath(f, D.ROOT), '换' if hit else '接'))
    if '--apply' in sys.argv:
        D.safe_write(f, nl.join(lines))
print('合计 %d 页%s' % (n, '' if '--apply' in sys.argv else '（没加 --apply，只报）'))
